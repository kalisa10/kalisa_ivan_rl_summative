"""Local-only HTTP API and static file server for the SmartCare Three.js simulation.

No patient information leaves this machine; all profiles are synthetic.
The 3D frontend animates episodes generated by the original Python Gymnasium env.
"""
from __future__ import annotations

import argparse
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import json
from pathlib import Path
from urllib.parse import parse_qs, urlsplit
import webbrowser

from environment import PatientNavigationEnv

HERE = Path(__file__).resolve().parent
ALGORITHMS = ("random", "dqn", "ppo", "a2c", "reinforce")


def load_selector(algorithm: str, checkpoint: str | None):
    if algorithm == "random":
        if checkpoint:
            raise ValueError("A random policy must not use a model checkpoint")
        return None
    if not checkpoint:
        raise ValueError(f"--model is required for {algorithm}; choose a trained .pth checkpoint")
    if not Path(checkpoint).is_file():
        raise FileNotFoundError(f"Checkpoint not found: {checkpoint}")
    if algorithm == "dqn":
        from training.dqn_training import load_model, greedy_action
        model = load_model(checkpoint)
    else:
        from training.pg_training import load_policy, greedy_action
        model = load_policy(algorithm, checkpoint)
    return lambda observation: greedy_action(model, observation)


def simulate(seed: int, algorithm: str, selector=None) -> dict:
    """One authentic three-step navigation episode; suitable for replay in 3D."""
    env = PatientNavigationEnv()
    try:
        obs, _ = env.reset(seed=seed)
        env.action_space.seed(seed + 900)  # Reproducible random-policy replay.
        profile = {
            "phone_access": bool(obs[0]),
            "travel_barrier": bool(obs[1]),
            "telehealth_access": bool(obs[2]),
            "missed_visit_risk": round(float(obs[3]), 3),
        }
        events = []
        total = 0.0
        while True:
            action = int(selector(obs)) if selector is not None else int(env.action_space.sample())
            obs, reward, terminated, truncated, info = env.step(action)
            total += reward
            event = {
                "step": len(events) + 1,
                "action_id": action,
                "action": info["action"],
                "reward": round(float(reward), 4),
                "flags": [int(v) for v in obs[4:8]],
            }
            if terminated or truncated:
                event["attended"] = bool(info["attended"])
                event["probability"] = round(float(info["attendance_probability"]), 4)
            events.append(event)
            if terminated or truncated:
                return {
                    "algorithm": algorithm.upper(),
                    "seed": seed,
                    "profile": profile,
                    "events": events,
                    "total_reward": round(total, 4),
                    "connected": bool(info["attended"]),
                    "attendance_probability": round(float(info["attendance_probability"]), 4),
                    "note": "Synthetic patient simulation, not medical advice or a real patient",
                }
    finally:
        env.close()


def make_handler(algorithm, selector):
    class Handler(BaseHTTPRequestHandler):
        def do_GET(self):
            path = urlsplit(self.path)
            if path.path == "/api/episode":
                try:
                    raw = parse_qs(path.query).get("seed", ["42"])[0]
                    seed = int(raw)
                    if not 0 <= seed <= 2_147_483_647:
                        raise ValueError("Seed must be between 0 and 2147483647")
                    payload = simulate(seed, algorithm, selector)
                    data = json.dumps(payload, allow_nan=False).encode("utf-8")
                    self.send_response(200)
                    self.send_header("Content-Type", "application/json; charset=utf-8")
                except (ValueError, RuntimeError) as exc:
                    data = json.dumps({"error": str(exc)}).encode("utf-8")
                    self.send_response(400)
                    self.send_header("Content-Type", "application/json; charset=utf-8")
                self.send_header("Cache-Control", "no-store")
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)
                return
            if path.path not in ("/", "/index.html"):
                self.send_error(404)
                return
            data = (HERE / "index.html").read_bytes()
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Security-Policy", "default-src 'self' https://cdn.jsdelivr.net; script-src 'self' 'unsafe-inline' https://cdn.jsdelivr.net; style-src 'self' 'unsafe-inline'; connect-src 'self'; img-src 'self' data:; font-src 'self' data:")
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)

        def log_message(self, fmt, *args):
            if not args or not str(args[1] if len(args) > 1 else "").startswith("200"):
                super().log_message(fmt, *args)

    return Handler


def main():
    parser = argparse.ArgumentParser(description="SmartCare Three.js interactive 3D simulation")
    parser.add_argument("--algorithm", choices=ALGORITHMS, default="random")
    parser.add_argument("--model", help="Path to the trained .pth checkpoint")
    parser.add_argument("--port", type=int, default=8765)
    parser.add_argument("--no-browser", action="store_true")
    args = parser.parse_args()
    selector = load_selector(args.algorithm, args.model)
    server = ThreadingHTTPServer(("127.0.0.1", args.port), make_handler(args.algorithm, selector))
    url = f"http://127.0.0.1:{args.port}/"
    print(f"SmartCare advanced 3D simulation: {url}", flush=True)
    print(f"Policy: {args.algorithm.upper()} | checkpoint: {args.model or '(random)'}", flush=True)
    print("Replay uses real environment steps; press Ctrl+C to stop the server.", flush=True)
    print("Three.js loads from jsDelivr CDN and needs internet on first launch.", flush=True)
    if not args.no_browser:
        webbrowser.open(url)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("Stopping 3D server.")
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
